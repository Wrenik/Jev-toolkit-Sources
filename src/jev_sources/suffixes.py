def is_multi_tenant(host: str) -> bool:
    return host in MULTI_TENANT


@lru_cache(maxsize=1)
def _load() -> tuple[frozenset[str], frozenset[str], frozenset[str], dict[str, str]]:
    plain, wild, exc = set(), set(), set()
    meta: dict[str, str] = {}
    text = resources.files("jev_sources").joinpath("data/public_suffix_icann.dat").read_text(encoding="utf-8")
    for line in text.splitlines():
        if line.startswith("#"):
            m = re.match(r"# (PSL version|Generated|Rules):\s+(\S+)", line)
            if m:
                meta[m.group(1)] = m.group(2)
        elif line.startswith("!"):
            exc.add(line[1:])
        elif line.startswith("*."):
            wild.add(line[2:])
        elif line:
            plain.add(line)
    return frozenset(plain), frozenset(wild), frozenset(exc), meta


def snapshot_info() -> dict[str, str]:
    """{'PSL version': ..., 'Generated': ..., 'Rules': ...} of the bundled snapshot."""
    return dict(_load()[3])


def public_suffix(host: str) -> str:
    """The public suffix of `host` per the PSL algorithm over the ICANN section (unknown TLDs: the TLD, rule `*`)."""
    plain, wild, exc, _ = _load()
    labels = host.split(".")
    for i in range(len(labels)):  # longest candidate first; an exception rule beats everything
        cand = ".".join(labels[i:])
        if cand in exc:
            return ".".join(labels[i + 1 :])
    for i in range(len(labels)):
        cand = ".".join(labels[i:])
        parent = ".".join(labels[i + 1 :])
        if cand in plain or (parent and parent in wild):
            return cand
    return labels[-1]


def is_icann_suffix(host: str) -> bool:
    """True when `host` itself is a listed ICANN public suffix (`gov.uk`, `co.jp`, `gov`), a valid `suffix =` value."""
    plain, wild, exc, _ = _load()
    if host in plain:
        return True
    parent = host.partition(".")[2]
    return bool(parent) and parent in wild and host not in exc


def registrable_domain(host: str) -> str:
    """The suffix plus one label (`legislation.gov.uk` -> `legislation.gov.uk`; `a.b.example.co.uk` -> `example.co.uk`); '' if none."""
    suf = public_suffix(host)
    if host == suf:
        return ""
    return ".".join(host[: -len(suf) - 1].split(".")[-1:] + [suf])


def is_public_suffix(host: str) -> bool:
    """True for a registry public suffix (PSL ICANN section) or a known multi-tenant suffix."""
    return host in MULTI_TENANT or ("." in host and public_suffix(host) == host)


def user_content_host(host: str) -> bool:
    return host in USER_CONTENT
