"""Public-suffix awareness without a network call.

A rule `host = "github.io", subdomains = true` approves every GitHub Pages site in the world; `co.uk` approves every
British company. Browsers solve this with the Public Suffix List (PSL, publicsuffix.org). This module bundles a
snapshot of the PSL's ICANN section (`data/public_suffix_icann.dat`, generated by `tools/update_suffixes.py`,
MPL-2.0, dated in its header) and implements the PSL matching algorithm (wildcards, exceptions, default `*`).

It is used only when a policy is WRITTEN (validate / explain), never to decide a URL, with one exception: the
`suffix = "gov.uk"` rule, which is the deliberate, explicit way to approve every registrable domain under a
registry-controlled suffix, and which must name a suffix that is really in the list.

The PSL's PRIVATE section (hosting platforms) is not bundled: it is large and changes weekly. `MULTI_TENANT` below is
a short hand-made approximation of the platforms people actually put in policies. `USER_CONTENT` lists hosts where
anyone can publish under one name.
"""

